#!/usr/bin/env python3
"""Restores the daily household backup (backups/live/*.json) -- and PROVES the backup is restorable.

    python3 tools/restore_live.py --sql restore.sql     write idempotent upsert SQL you can run in the
                                                        Supabase SQL editor (tables must already exist)
    python3 tools/restore_live.py --check               round-trip test in the local scratch Postgres:
                                                        loads the backup into a throwaway database, runs the
                                                        restore SQL TWICE, and compares every row back to the
                                                        JSON (also fails if a backup file is missing/empty/damaged)

The generated SQL only inserts or updates rows (on conflict -> update); it never deletes anything, and an
older backup row never overwrites a newer live row because migrations/014's trigger skips stale updates.
"""
import datetime, json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BACKUP = ROOT / 'backups' / 'live'
PSQL = '/Applications/Postgres.app/Contents/Versions/latest/bin/psql'
PK = {'cook_log': ['id'], 'plan_days': ['slot_id'], 'inventory_items': ['id'], 'shopping_lists': ['id'],
      'prefs': ['household_id'], 'interested_recipes': ['recipe_id', 'household_id'], 'family_submissions': ['id'],
      'client_errors': ['id'], 'recipe_collections': ['id'], 'collection_items': ['id']}


def load():
    data = {}
    for t in PK:
        f = BACKUP / f'{t}.json'
        if not f.exists():
            if t in ('recipe_collections', 'collection_items'):
                continue            # only exist after migration 016
            raise SystemExit(f'backup file missing: {f}')
        rows = json.loads(f.read_text(encoding='utf-8'))
        if not isinstance(rows, list):
            raise SystemExit(f'{f.name}: not a list of rows')
        data[t] = rows
    return data


def restore_sql(data):
    out = ['-- generated by tools/restore_live.py: upserts only, nothing is deleted', 'begin;']
    for t, rows in data.items():
        if not rows:
            out.append(f'-- {t}: no rows')
            continue
        cols = sorted({c for r in rows for c in r})
        collist = ', '.join(f'"{c}"' for c in cols)
        sets = ', '.join(f'"{c}" = excluded."{c}"' for c in cols if c not in PK[t])
        payload = json.dumps(rows, ensure_ascii=False).replace('$', r'\$') if False else json.dumps(rows, ensure_ascii=False)
        tag = '$restore$'
        assert tag not in payload
        out.append(f'insert into {t} ({collist}) select {collist} from json_populate_recordset(null::{t}, {tag}{payload}{tag}) '
                   f'on conflict ({", ".join(PK[t])}) do update set {sets or ", ".join(f"{c} = excluded.{c}" for c in PK[t])};')
    out.append('commit;')
    return '\n'.join(out) + '\n'


TS = re.compile(r'^(\d{4}-\d\d-\d\d)[T ](\d\d:\d\d:\d\d)(\.\d+)?(Z|[+-]\d\d(?::?\d\d)?)?$')


def instant(s):
    """a timestamp string as a point in time (None if it isn't one) -- Postgres spells the same instant in local time"""
    m = TS.match(s) if isinstance(s, str) else None
    if not m:
        return None
    tz = m.group(4) or '+00:00'
    tz = '+00:00' if tz == 'Z' else (tz if ':' in tz or len(tz) > 3 else tz + ':00')
    if ':' not in tz: tz = tz[:3] + ':' + tz[3:]
    frac = (m.group(3) or '.0')[1:7].ljust(6, '0')
    return datetime.datetime.fromisoformat(f'{m.group(1)}T{m.group(2)}.{frac}{tz}')


def sql_type(values):
    vals = [v for v in values if v is not None]
    if not vals:
        return 'text'
    if all(isinstance(v, bool) for v in vals): return 'boolean'
    if all(isinstance(v, int) and not isinstance(v, bool) for v in vals): return 'bigint'
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals): return 'double precision'
    if any(isinstance(v, (list, dict)) for v in vals): return 'jsonb'
    if all(isinstance(v, str) and len(v) >= 19 and v[4] == '-' and v[10] in 'T ' for v in vals): return 'timestamptz'
    return 'text'


def psql(db, sql, check=True):
    r = subprocess.run([PSQL, '-d', db, '-q', '-X', '-v', 'ON_ERROR_STOP=1', '-At'], input=sql, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise SystemExit('psql failed: ' + r.stderr[-600:])
    return r.stdout


def check():
    data = load()
    db = 'cb_restore_check'
    try:
        psql('postgres', 'select 1;')
    except SystemExit as e:
        # no scratch database available here (Postgres.app not running, or macOS has not approved this
        # process to connect): that is an environment gap, not a bad backup
        print('restore check SKIPPED: cannot reach the local scratch Postgres (' + str(e)[:120].replace('\n', ' ') + ')')
        return
    psql('postgres', f'drop database if exists {db};')
    psql('postgres', f'create database {db};')
    try:
        for t, rows in data.items():
            cols = sorted({c for r in rows for c in r})
            defs = ', '.join(f'"{c}" {sql_type([r.get(c) for r in rows])}' for c in cols) or 'id text'
            pk = ', '.join(f'"{c}"' for c in PK[t])
            psql(db, f'create table {t} ({defs}, primary key ({pk}));' if rows else f'create table {t} (id text);')
        sql = restore_sql(data)
        psql(db, sql); psql(db, sql)                       # twice: restoring must be repeatable
        problems = []
        for t, rows in data.items():
            if not rows:
                continue
            got = json.loads(psql(db, f'select coalesce(json_agg(row_to_json(x)), \'[]\') from {t} x;') or '[]')
            key = lambda r: tuple(str(r.get(c)) for c in PK[t])
            if len(got) != len(rows):
                problems.append(f'{t}: {len(got)} rows restored, backup has {len(rows)}'); continue
            by = {key(r): r for r in got}
            for r in rows:
                g = by.get(key(r))
                if g is None: problems.append(f'{t}: row {key(r)} missing after restore'); continue
                for c, v in r.items():
                    gv = g.get(c)
                    if instant(v) is not None and instant(gv) is not None:
                        if instant(v) != instant(gv): problems.append(f'{t} {key(r)} column {c}: {v!r} != {gv!r}')
                        continue
                    if gv != v: problems.append(f'{t} {key(r)} column {c}: backup {v!r} != restored {gv!r}')
        total = sum(len(r) for r in data.values())
        if problems:
            print('\n'.join(problems[:12])); sys.exit(f'RESTORE CHECK FAILED ({len(problems)} problem(s))')
        print(f'restore check OK: {total} rows across {sum(1 for r in data.values() if r)} tables restored twice into a scratch database and matched the backup exactly')
    finally:
        psql('postgres', f'drop database if exists {db};', check=False)


if __name__ == '__main__':
    if '--check' in sys.argv:
        check()
    elif '--sql' in sys.argv:
        out = sys.argv[sys.argv.index('--sql') + 1]
        pathlib.Path(out).write_text(restore_sql(load()), encoding='utf-8')
        print('wrote', out)
    else:
        print(__doc__)
